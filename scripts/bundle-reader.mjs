// Inlines core + prefs + the element into one ESM file: dist/legible-reader.js (no imports, no dependencies).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(resolve(root, p), 'utf8');
const strip = (s) => s.replace(/^import[^;]*;\n/gm, '').replace(/^export \{[^}]*\} from '[^']*';\n/gm, '').replace(/^export default \w+;\n/gm, '').replace(/^export (const|function|class|let) /gm, '$1 ').replace(/^export \{[^}]*\};\n/gm, '');
const parts = ['packages/core/src/limits.js', 'packages/core/src/color.js', 'packages/core/src/contrast.js', 'packages/core/src/guard.js', 'packages/reader/src/prefs.js', 'packages/reader/src/legible-reader.js'];
const out = `// Legible Reader — generated by scripts/bundle-reader.mjs. Do not edit.\n(() => {\n${parts.map((p) => `// ---- ${p}\n${strip(read(p))}`).join('\n')}\n})();\n`;
mkdirSync(resolve(root, 'dist'), { recursive: true });
writeFileSync(resolve(root, 'dist/legible-reader.js'), out);
console.log('dist/legible-reader.js ' + out.length + ' bytes');
